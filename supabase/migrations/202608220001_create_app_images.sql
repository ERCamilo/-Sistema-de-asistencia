create or replace function public.swap_app_image_pointer(
    p_firebase_uid text,
    p_category text,
    p_owner_type text,
    p_owner_id text,
    p_asset_id text,
    p_variant text,
    p_storage_path text,
    p_mime_type text,
    p_file_size_bytes bigint,
    p_original_name text
)
returns table (
    previous_storage_path text,
    current_storage_path text,
    category text,
    owner_type text,
    owner_id text,
    asset_id text,
    variant text,
    mime_type text,
    file_size_bytes bigint,
    original_name text,
    uploaded_at timestamptz,
    updated_at timestamptz
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_previous_storage_path text;
    v_asset public.app_images%rowtype;
begin
    perform pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended(
            pg_catalog.concat_ws(
                chr(31),
                p_firebase_uid,
                p_category,
                p_owner_type,
                p_owner_id,
                p_asset_id,
                p_variant
            ),
            0
        )
    );

    select image.storage_path
    into v_previous_storage_path
    from public.app_images as image
    where image.firebase_uid = p_firebase_uid
      and image.category = p_category
      and image.owner_type = p_owner_type
      and image.owner_id = p_owner_id
      and image.asset_id = p_asset_id
      and image.variant = p_variant
    for update;

    insert into public.app_images (
        firebase_uid,
        category,
        owner_type,
        owner_id,
        asset_id,
        variant,
        storage_bucket,
        storage_path,
        mime_type,
        file_size_bytes,
        original_name,
        uploaded_at,
        updated_at
    ) values (
        p_firebase_uid,
        p_category,
        p_owner_type,
        p_owner_id,
        p_asset_id,
        p_variant,
        'app-images',
        p_storage_path,
        p_mime_type,
        p_file_size_bytes,
        p_original_name,
        clock_timestamp(),
        clock_timestamp()
    )
    on conflict on constraint app_images_logical_key
    do update set
        storage_bucket = excluded.storage_bucket,
        storage_path = excluded.storage_path,
        mime_type = excluded.mime_type,
        file_size_bytes = excluded.file_size_bytes,
        original_name = excluded.original_name,
        uploaded_at = excluded.uploaded_at,
        updated_at = excluded.updated_at
    returning * into v_asset;

    return query
    select
        v_previous_storage_path,
        v_asset.storage_path,
        v_asset.category,
        v_asset.owner_type,
        v_asset.owner_id,
        v_asset.asset_id,
        v_asset.variant,
        v_asset.mime_type,
        v_asset.file_size_bytes,
        v_asset.original_name,
        v_asset.uploaded_at,
        v_asset.updated_at;
end;
$$;

create or replace function public.delete_app_image_pointer_cas(
    p_firebase_uid text,
    p_category text,
    p_owner_type text,
    p_owner_id text,
    p_asset_id text,
    p_variant text,
    p_expected_storage_path text
)
returns boolean
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_deleted boolean;
begin
    perform pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended(
            pg_catalog.concat_ws(
                chr(31),
                p_firebase_uid,
                p_category,
                p_owner_type,
                p_owner_id,
                p_asset_id,
                p_variant
            ),
            0
        )
    );

    delete from public.app_images as image
    where image.firebase_uid = p_firebase_uid
      and image.category = p_category
      and image.owner_type = p_owner_type
      and image.owner_id = p_owner_id
      and image.asset_id = p_asset_id
      and image.variant = p_variant
      and image.storage_path = p_expected_storage_path
    returning true into v_deleted;

    return coalesce(v_deleted, false);
end;
$$;

