create table if not exists public.app_images (
    id bigint generated by default as identity primary key,
    firebase_uid text not null
        check (firebase_uid ~ '^[A-Za-z0-9_-]{1,128}$'),
    category text not null
        check (category in ('employee-profile', 'worksite-photo', 'company-image')),
    owner_type text not null
        check (
            (category = 'employee-profile' and owner_type = 'employee') or
            (category = 'worksite-photo' and owner_type = 'worksite') or
            (category = 'company-image' and owner_type = 'company')
        ),
    owner_id text not null
        check (owner_id ~ '^[A-Za-z0-9][A-Za-z0-9_-]{0,79}$'),
    asset_id text not null
        check (asset_id ~ '^[A-Za-z0-9][A-Za-z0-9_-]{0,79}$'),
    variant text not null
        check (
            (category in ('employee-profile', 'worksite-photo') and variant in ('thumbnail', 'original')) or
            (category = 'company-image' and variant in ('thumbnail', 'original', 'logo'))
        ),
    storage_bucket text not null default 'app-images'
        check (storage_bucket = 'app-images'),
    storage_path text not null
        check (
            storage_path = concat(
                firebase_uid, '/', category, '/', owner_type, '/', owner_id, '/',
                asset_id, '/', variant, '/versions/', right(storage_path, 36)
            ) and
            right(storage_path, 36) ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
        ),
    mime_type text not null
        check (mime_type in ('image/jpeg', 'image/png', 'image/webp')),
    file_size_bytes bigint not null
        check (
            (category = 'employee-profile' and file_size_bytes between 1 and 5242880) or
            (category in ('worksite-photo', 'company-image') and file_size_bytes between 1 and 10485760)
        ),
    original_name text
        check (original_name is null or char_length(original_name) <= 255),
    uploaded_at timestamptz not null default now(),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint app_images_logical_key
        unique (firebase_uid, category, owner_type, owner_id, asset_id, variant),
    unique (storage_bucket, storage_path)
);

create index if not exists app_images_owner_lookup_idx
    on public.app_images (
        firebase_uid,
        category,
        owner_type,
        owner_id,
        updated_at desc
    );

alter table public.app_images enable row level security;

revoke all on table public.app_images from anon, authenticated;
revoke all on sequence public.app_images_id_seq from anon, authenticated;
grant all on table public.app_images to service_role;
grant usage, select on sequence public.app_images_id_seq to service_role;

comment on table public.app_images is
    'Private, tenant-scoped application images managed only by the app-images Edge Function.';

