#!/usr/bin/env node
/**
 * Generates sw-precache-manifest.js: every same-origin asset the app needs to
 * boot, so the Service Worker can precache the WHOLE module graph at install.
 *
 * Why: the hand-written APP_SHELL in sw.js only listed ~160 files while the
 * boot graph reaches ~370 ES modules. Any module missing from the precache is
 * only cached on the *second* online visit, so right after each deploy the
 * app could not start offline (module graph failed → "No pudimos iniciar").
 *
 * Sources walked:
 *   - index.html: <script src>, <link rel="stylesheet" href> and the static
 *     imports of its inline <script type="module"> blocks.
 *   - every reachable relative static import/export-from and literal import().
 *
 * URLs keep the exact spelling the page requests (including query strings such
 * as `?v=2`), because Cache Storage matches on the full URL.
 *
 * Usage:
 *   node scripts/sw-precache.cjs          # write sw-precache-manifest.js
 *   node scripts/sw-precache.cjs --check  # exit 1 if the manifest is stale
 * Kept in sync by js/tests/ServiceWorkerPrecacheManifest.test.js.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const MANIFEST_FILE = 'sw-precache-manifest.js';

const STATIC_IMPORT_RE = /(?:^|[\s;}])(?:import|export)\s*(?:[\w$*{}\s,]+?\s*from\s*)?['"]([^'"\n]+)['"]/g;
const DYNAMIC_IMPORT_RE = /\bimport\(\s*['"]([^'"\n]+)['"]\s*\)/g;
const SCRIPT_SRC_RE = /<script\b[^>]*\bsrc=["']([^"']+)["'][^>]*>/gi;
const STYLESHEET_RE = /<link\b(?=[^>]*\brel=["']stylesheet["'])[^>]*\bhref=["']([^"']+)["'][^>]*>/gi;
const INLINE_MODULE_RE = /<script\b[^>]*\btype=["']module["'][^>]*>([\s\S]*?)<\/script>/gi;

function isRelative(spec) {
    // Same-origin relative URL: no scheme (https:, data:…) and not root/protocol-relative.
    return !/^([a-z][a-z0-9+.-]*:|\/)/i.test(spec);
}

function splitQuery(url) {
    const i = url.search(/[?#]/);
    return i === -1 ? [url, ''] : [url.slice(0, i), url.slice(i)];
}

function importSpecifiers(source) {
    const specs = [];
    for (const m of source.matchAll(STATIC_IMPORT_RE)) specs.push(m[1]);
    for (const m of source.matchAll(DYNAMIC_IMPORT_RE)) specs.push(m[1]);
    return specs.filter((s) => s.startsWith('./') || s.startsWith('../'));
}

/**
 * @param {string} root project root
 * @returns {string[]} sorted './'-prefixed URLs relative to root
 */
function collectPrecacheAssets(root) {
    const assets = new Set();
    const visited = new Set();
    const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');

    const addFromRoot = (url) => {
        if (!isRelative(url)) return null;
        const [file, query] = splitQuery(url.replace(/^\.\//, ''));
        const abs = path.resolve(root, file);
        if (!abs.startsWith(root + path.sep) || !fs.existsSync(abs)) return null;
        assets.add('./' + path.relative(root, abs).split(path.sep).join('/') + query);
        return abs;
    };

    const walkModule = (abs) => {
        if (visited.has(abs)) return;
        visited.add(abs);
        const source = fs.readFileSync(abs, 'utf8');
        for (const spec of importSpecifiers(source)) {
            const [file] = splitQuery(spec);
            const target = path.resolve(path.dirname(abs), file);
            // Imports that only appear in comments may point nowhere: skip them.
            if (!target.startsWith(root + path.sep) || !fs.existsSync(target)) continue;
            assets.add('./' + path.relative(root, target).split(path.sep).join('/'));
            walkModule(target);
        }
    };

    for (const m of html.matchAll(STYLESHEET_RE)) addFromRoot(m[1]);
    for (const m of html.matchAll(SCRIPT_SRC_RE)) {
        const abs = addFromRoot(m[1]);
        if (abs && abs.endsWith('.js')) walkModule(abs);
    }
    for (const m of html.matchAll(INLINE_MODULE_RE)) {
        for (const spec of importSpecifiers(m[1])) {
            const abs = addFromRoot(spec);
            if (abs) walkModule(abs);
        }
    }

    return [...assets].sort();
}

function renderManifest(assets) {
    return [
        '// GENERATED by scripts/sw-precache.cjs — do not edit by hand.',
        '// Regenerate with: npm run sw:precache',
        '// Same-origin assets reachable from index.html at boot; sw.js precaches',
        '// them on install so the app can start offline right after a deploy.',
        'self.SW_PRECACHE_MANIFEST = [',
        ...assets.map((a) => `    ${JSON.stringify(a)},`),
        '];',
        ''
    ].join('\n');
}

function main(argv) {
    const root = path.resolve(__dirname, '..');
    const expected = renderManifest(collectPrecacheAssets(root));
    const target = path.join(root, MANIFEST_FILE);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;

    if (argv.includes('--check')) {
        if (current !== expected) {
            console.error(`✗ ${MANIFEST_FILE} is stale. Run: npm run sw:precache`);
            return 1;
        }
        console.log(`✓ ${MANIFEST_FILE} is up to date`);
        return 0;
    }
    if (current !== expected) fs.writeFileSync(target, expected);
    console.log(`✓ ${MANIFEST_FILE}: ${expected.split('\n').filter((l) => l.startsWith('    "')).length} assets`);
    return 0;
}

module.exports = { collectPrecacheAssets, renderManifest, MANIFEST_FILE };

if (require.main === module) process.exitCode = main(process.argv.slice(2));
